def build():
    seen = set()
    pools: dict[int, list[str]] = {length: [] for length in TARGET}

    problems = []
    for raw in CANDIDATES:
        word = raw.strip()
        if not PERSIAN.match(word):
            problems.append(f"کلمهٔ غیرِفارسی: {word!r}")
            continue
        if word in seen:
            problems.append(f"کلمهٔ تکراری: {word!r}")
            continue
        seen.add(word)
        pools.setdefault(len(word), []).append(word)

    # فقط کلمه‌هایی که در طولِ هدف جا دارند نگه داشته می‌شوند.
    selected = []
    for length in sorted(TARGET):
        need = TARGET[length]
        pool = [w for w in pools.get(length, []) if len(w) == length]
        if len(pool) < need:
            problems.append(
                f"{length} حرفی: {need} کلمه لازم است، فقط {len(pool)} هست")
            continue
        selected.extend(pool[:need])

    if problems:
        print("⛔ بانکِ کلمات رد شد:")
        for item in problems:
            print("  •", item)
        return 1

    if len(selected) != TOTAL:
        print(f"⛔ تعداد {len(selected)} شد، باید {TOTAL} باشد")
        return 1

    # کلمه‌ها کوتاه→بلند، و در هر طول به همان ترتیبِ فهرست (ساده→سخت).
    selected.sort(key=lambda w: len(w))
    stages = [
        {"stage": index, "word": word, "letters": len(word)}
        for index, word in enumerate(selected, start=1)
    ]

    histogram = {}
    for item in stages:
        histogram[str(item["letters"])] = histogram.get(
            str(item["letters"]), 0) + 1

    payload = {
        "_meta": {
            "game": "word_puzzle",
            "total": TOTAL,
            "written_by": "tools/build_word_puzzle_words.py",
            "histogram": histogram,
        },
        "words": [
            {"stage": item["stage"], "word": item["word"]}
            for item in stages
        ],
    }

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"✅ نوشته شد: {OUT} — {TOTAL} مرحله")
    print("   طول‌ها:", histogram)
    print("   سه‌تای اول:", [i["word"] for i in stages[:3]])
    print("   سه‌تای آخر:", [i["word"] for i in stages[-3:]])
    return 0


if __name__ == "__main__":
    sys.exit(build())
