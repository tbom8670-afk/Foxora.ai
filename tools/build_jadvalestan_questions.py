def normalize(value: str) -> str:
    text = unicodedata.normalize("NFC", str(value or "")).strip()
    return " ".join(text.split())


PERSIAN = re.compile(r"^[\u0621-\u06CC\u200C]+$")


def main() -> int:
    errors = []

    # ۱) یکتاییِ سوال‌ها
    seen_questions = {}
    for topic, level, question, answer in Q:
        key = normalize(question)
        if key in seen_questions:
            errors.append(f"سوالِ تکراری: {question!r}")
        seen_questions[key] = answer

    # ۲) جواب‌ها: یک کلمه، فقط حروفِ فارسی، بدونِ رقم
    answers = {}
    for topic, level, question, answer in Q:
        if not answer or " " in normalize(answer):
            errors.append(f"جوابِ چندکلمه‌ای: {question!r} → {answer!r}")
            continue
        if any(ch.isdigit() for ch in answer):
            errors.append(f"جوابِ عددی: {question!r} → {answer!r}")
        if not PERSIAN.match(answer):
            errors.append(f"جوابِ غیرفارسی: {question!r} → {answer!r}")
        answers.setdefault(answer, []).append(question)

    # ۳) جواب‌های دوپهلو (یک جواب برای دو سوال مختلف اشکالی ندارد، ولی
    #    متنِ سوال باید یکتا باشد) — فقط گزارش می‌کنیم.
    duplicates = {a: q for a, q in answers.items() if len(q) > 1}

    print(f"تعدادِ سوال‌ها: {len(Q)}")
    if duplicates:
        print(f"جواب‌های مشترک ({len(duplicates)}):")
        for answer, questions in sorted(duplicates.items()):
            print(f"  • {answer} ← {len(questions)} سوال")

    if errors:
        print("\n❌ خطاها:")
        for error in errors:
            print("  -", error)
        return 1

    # ۳٫۵) بازتنظیمِ سطح: سوال‌های قطعاً آسان، «آسان» شوند تا الگوی
    #      «چند آسان، بعد متوسط/سخت» تا آخرِ بازی دوام بیاورد.
    def _level(question, level):
        if question in EASIER:
            return 1
        if question in MEDIUM:
            return 2
        return level

    Q[:] = [
        (topic, _level(question, level), question, answer)
        for topic, level, question, answer in Q
    ]

    # ۴) ترتیب: سختی با الگو قاطی می‌شود و موضوع‌ها به‌صورتِ چرخشی
    #    (round-robin) پخش می‌شوند تا هیچ‌وقت پشتِ‌سرهم تکرار نشوند.
    from collections import defaultdict, deque

    pools = {1: defaultdict(deque), 2: defaultdict(deque), 3: defaultdict(deque)}
    for topic, level, question, answer in Q:
        pools[level][topic].append((topic, level, question, answer))
    for level in pools:
        for topic in pools[level]:
            pools[level][topic] = deque(
                sorted(pools[level][topic], key=lambda item: item[2])
            )

    total_by_topic = {}
    for topic, _level, _question, _answer in Q:
        total_by_topic[topic] = total_by_topic.get(topic, 0) + 1

    pattern = [1, 1, 2, 1, 1, 3, 1, 2, 1, 1, 2, 3]
    ordered = []
    last_topic = None
    last_used = {}
    for cursor in range(len(Q)):
        wanted = pattern[cursor % len(pattern)]
        choice = None
        for level in (wanted, 1, 2, 3):
            # نسبتِ «باقی‌مانده» هر موضوع: هر موضوع متناسب با سهمش در کلِ
            # بازی پخش می‌شود، پس آخرِ بازی یک موضوع تنها نمی‌ماند.
            candidates = [
                (
                    -(len(queue) / total_by_topic[topic]),
                    last_used.get(topic, -1),
                    topic,
                )
                for topic, queue in pools[level].items()
                if queue and topic != last_topic
            ]
            if candidates:
                candidates.sort()
                topic = candidates[0][2]
                choice = pools[level][topic].popleft()
                break
        if choice is None:
            for level in (wanted, 1, 2, 3):
                for topic, queue in pools[level].items():
                    if queue:
                        choice = queue.popleft()
                        break
                if choice:
                    break
        if choice is None:
            break
        ordered.append(choice)
        last_topic = choice[0]
        last_used[choice[0]] = cursor

    stages = []
    for number, (topic, level, question, answer) in enumerate(ordered, start=1):
        stages.append({
            "stage": number,
            "topic": topic,
            "difficulty": "آسان" if level == 1 else ("متوسط" if level == 2 else "سخت"),
            "question": question,
            "answer": answer,
        })

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        json.dumps(
            {
                "_meta": {
                    "game": "جدولستان",
                    "total": len(stages),
                    "generated_by": "tools/build_jadvalestan_questions.py",
                    "note": "طولِ جواب با کد از روی خودِ جواب حساب شده است؛ دستی نوشته نشده.",
                },
                "questions": stages,
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )

    counts = {}
    for stage in stages:
        counts[stage["difficulty"]] = counts.get(stage["difficulty"], 0) + 1
    print(f"✅ نوشته شد: {OUT.relative_to(ROOT)} — {len(stages)} مرحله")
    print("   سختی:", counts)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
