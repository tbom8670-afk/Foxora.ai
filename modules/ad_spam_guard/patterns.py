"""الگوهای تشخیص ربات‌های تبلیغاتی + نرمال‌سازی مقاوم.

این ربات‌ها با **نام/یوزرنیم خودشان** یا **سری ایموجیِ مشخص** معرفی می‌شوند و
به پیام‌های عادیِ کاربران ریپلای می‌کنند. بنابراین تشخیص فقط بر پایهٔ محتوای
پیام کافی نیست و باید هویتِ فرستنده هم بررسی شود.

نرمال‌سازی عمداً «مقاوم» است، چون این ربات‌ها از تکرار حروف («استرررررر») و
کاراکترهای نامرئی برای عبور از فیلترها استفاده می‌کنند.
"""
from __future__ import annotations

import re

# ---------------------------------------------------------------------------
# نرمال‌سازی
# ---------------------------------------------------------------------------

# یکسان‌سازی حروف عربی/فارسی تا «استر» با «استر» و «ك» با «ک» یکی شوند.
_CHAR_MAP = str.maketrans(
    {
        "ي": "ی", "ى": "ی", "ئ": "ی",
        "ك": "ک", "ک": "ک",
        "ة": "ه", "ۀ": "ه", "ه": "ه",
        "أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا",
        "ؤ": "و",
        "٠": "0", "١": "1", "٢": "2", "٣": "3", "٤": "4",
        "٥": "5", "٦": "6", "٧": "7", "٨": "8", "٩": "9",
        "۰": "0", "۱": "1", "۲": "2", "۳": "3", "۴": "4",
        "۵": "5", "۶": "6", "۷": "7", "۸": "8", "۹": "9",
    }
)

# کاراکترهای نامرئی/کنترلی که اسپمرها برای شکستن کلمات می‌گذارند.
_INVISIBLE_RE = re.compile(
    "[\u200b\u200c\u200d\u200e\u200f\u2060\ufeff\u00ad"
    "\u2061\u2062\u2063\u2064\u180e\ufe0f"
    "\u0640\u0641\u2007\u202f]"
)

# ۳ بار یا بیشتر تکرارِ یک کاراکتر → یک بار («استرررررر» → «استر»).
_RUN_RE = re.compile(r"(.)\1{2,}", re.UNICODE)

_EMOJI_RE = re.compile(
    "[\U0001F000-\U0001FAFF"
    "\U00002600-\U000027BF"
    "\U0001F1E6-\U0001F1FF"
    "\U00002190-\U000021FF"
    "\U00002B00-\U00002BFF"
    "\U0000FE00-\U0000FE0F]",
    re.UNICODE,
)

_WS_RE = re.compile(r"\s+")

# جداکننده‌هایی که در یوزرنیم و نام ربات‌ها به‌جای فاصله می‌آیند. تبدیلشان
# به فاصله لازم است، وگرنه «عسل_استررررررومو_ببین» با مارکرِ «عسل استر»
# مطابقت نمی‌کند و ربات فرار می‌کند.
_SEP_RE = re.compile(r"[_\-.+|/\\]+")


def normalize(text: str | None) -> str:
    """متن را برای مقایسهٔ الگوها یکدست می‌کند.

    ترتیب مهم است: اول حذف نامرئی‌ها، بعد یکدست‌سازی حروف، بعد جمع‌کردن
    تکرارها، و در آخر فشرده‌سازی فاصله‌ها. اگر تکرارها قبل از حذف نامرئی‌ها
    جمع شوند، «اسـ​تر» (با کاراکتر نامرئی در وسط) از فیلتر فرار می‌کند.
    """
    if not text:
        return ""
    value = _INVISIBLE_RE.sub("", str(text))
    value = value.translate(_CHAR_MAP)
    value = _SEP_RE.sub(" ", value)
    value = _RUN_RE.sub(r"\1", value)
    return _WS_RE.sub(" ", value).strip().lower()


def emoji_signature(text: str | None) -> str:
    """فقط ایموجی‌های متن، به ترتیب ظاهر شدن (برای چک سری ایموجی)."""
    if not text:
        return ""
    return "".join(_EMOJI_RE.findall(str(text)))


def strip_emoji(text: str | None) -> str:
    if not text:
        return ""
    return _EMOJI_RE.sub(" ", str(text))


