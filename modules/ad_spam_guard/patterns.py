def sender_name(sender) -> str:
    """نام نمایشیِ فرستنده (first + last)."""
    if sender is None:
        return ""
    first = getattr(sender, "first_name", None)
    last = getattr(sender, "last_name", None)
    parts = [str(p) for p in (first, last) if p and str(p).strip()]
    return " ".join(parts).strip()


def sender_username(sender) -> str:
    if sender is None:
        return ""
    username = getattr(sender, "username", None)
    return str(username or "").strip().lstrip("@")
