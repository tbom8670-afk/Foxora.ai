# ---------------------------------------------------------------------------
# ۱) پیام تأییدیهٔ روشن‌کردن (پیش از فعال‌سازی واقعی)
# ---------------------------------------------------------------------------
CONFIRM_ENABLE_TEMPLATE = (
    "🦠ضد تبلیغ گر پیام های کاربران و ربات ها\n"
    "\n"
    "» شناسایی پیام های تبلیغاتی ربات ها\n"
    "\n"
    "» شناسایی پیام های عادی تبلیغات \n"
    "\n"
    "» شناسایی هرزنامه های ربات ها \n"
    "\n"
    "» شناسایی با دقت 85٪ هوش مصنوعی \n"
    "\n"
    "» شناسایی پیام های عادی ربات ها \n"
    "\n"
    "\n"
    "آیا این قابلیت فعال شود ؟ \n"
    "\n"
    "▪️تایید \n"
    "\n"
    "▫️ لغو"
)

# ---------------------------------------------------------------------------
# ۲) پیام‌های نتیجه
# ---------------------------------------------------------------------------
ENABLED_MESSAGE = "▫️ضد تبلیغ گر هوش مصنوعی روباه فعال شد"
DISABLED_MESSAGE = "▪️ضد تبلیغ گر هوش مصنوعی روباه خاموش شد"
CANCELLED_MESSAGE = "▫️لغو شد."

# ---------------------------------------------------------------------------
# ۳) پیام هشدار هنگام حذف پیام تبلیغاتی
#    {user}   — نمایش کاربر (مثل @username)
#    {count}  — تعداد اخطارهای کاربر
# ---------------------------------------------------------------------------
WARN_TEMPLATE = (
    "⚠️ کاربر  {user}\n"
    "\n"
    "پیام شما پاک شد | دلیل : تبلیغات گروهی\n"
    "\n"
    "تعداد اخطار : {count}\n"
    "\n"
    "انجام دهنده : هوش مصنوعی ضد تبلیغ"
)

# ---------------------------------------------------------------------------
# ۴) راهنمای دستور (برای لیست ادمینی)
# ---------------------------------------------------------------------------
HELP_HEADER = "💥برای فعال کردن ضد ربات های تبلیغ گر بنویسید"
HELP_ON = "تبلیغ گر روشن"
HELP_OFF = "تبلیغ گر خاموش"

# ---------------------------------------------------------------------------
# کلماتِ پاسخ به تأییدیه
# ---------------------------------------------------------------------------
CONFIRM_WORDS = frozenset({"تایید", "تأیید", "✅ تایید", "▪️تایید"})
CANCEL_WORDS = frozenset({"لغو", "❌ لغو", "▫️ لغو", "▫️لغو"})


def render_warn(user: str, count: int) -> str:
    """قالب هشدار را با مقدارهای واقعی می‌سازد."""
    try:
        return WARN_TEMPLATE.format(user=user, count=count)
    except Exception:
        # قالبِ خراب نباید کل قابلیت را از کار بیندازد.
        return WARN_TEMPLATE
